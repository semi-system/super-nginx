//go:build ignore

// Regenerates web/src/dnsProviders.ts from lego's provider .toml metadata.
// Run from the repo root after bumping the lego dependency:
//   go run web/gen/providers.go
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

type meta struct {
	Name          string
	Code          string
	Configuration struct {
		Credentials map[string]string
	}
}

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/go-acme/lego/v4").Output()
	if err != nil {
		panic(err)
	}
	dnsDir := filepath.Join(strings.TrimSpace(string(out)), "providers", "dns")

	entries, err := os.ReadDir(dnsDir)
	if err != nil {
		panic(err)
	}

	type prov struct {
		Code, Name string
		Env        []string
	}
	var provs []prov
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		tomlPath := filepath.Join(dnsDir, e.Name(), e.Name()+".toml")
		raw, err := os.ReadFile(tomlPath)
		if err != nil {
			continue // dir without matching toml (e.g. internal helpers)
		}
		var m meta
		if err := toml.Unmarshal(raw, &m); err != nil {
			panic(fmt.Sprintf("%s: %s", tomlPath, err))
		}
		if m.Code == "" {
			continue
		}
		env := make([]string, 0, len(m.Configuration.Credentials))
		for k := range m.Configuration.Credentials {
			env = append(env, k)
		}
		sort.Strings(env)
		provs = append(provs, prov{Code: m.Code, Name: m.Name, Env: env})
	}
	sort.Slice(provs, func(i, j int) bool { return provs[i].Name < provs[j].Name })

	var b strings.Builder
	b.WriteString("// GENERATED by web/gen/providers.go from lego provider metadata — do not edit.\n")
	b.WriteString("// Regenerate with:  go generate ./web/...\n")
	b.WriteString("export type DnsProvider = { code: string; name: string; env: string[] }\n\n")
	b.WriteString("export const dnsProviders: DnsProvider[] = [\n")
	for _, p := range provs {
		envs := make([]string, len(p.Env))
		for i, e := range p.Env {
			envs[i] = fmt.Sprintf("%q", e)
		}
		b.WriteString(fmt.Sprintf("  { code: %q, name: %q, env: [%s] },\n", p.Code, p.Name, strings.Join(envs, ", ")))
	}
	b.WriteString("]\n")

	dst := filepath.Join("web", "src", "dnsProviders.ts")
	if err := os.WriteFile(dst, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s (%d providers)\n", dst, len(provs))
}
